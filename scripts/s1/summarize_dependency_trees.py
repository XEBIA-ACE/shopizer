#!/usr/bin/env python3
"""S1 dependency conflict report generator (FR-S1-005..FR-S1-010, S1-AC3..S1-AC5).

Story b2ec327d-0260-5051-b2b9-e8e046c072a4. Reads the per-module
`mvn dependency:tree` outputs (resolved + verbose) written by
dependency-audit.sh and emits a deterministic markdown summary.
"""
import re
import sys
from pathlib import Path

MODULES = ["shopizer", "sm-core-model", "sm-core-modules", "sm-core", "sm-shop-model", "sm-shop"]

FOCUS_GROUPS = [
    ("Spring Boot", lambda g, a: g == "org.springframework.boot"),
    ("AspectJ", lambda g, a: g == "org.aspectj"),
    ("SLF4J", lambda g, a: g == "org.slf4j"),
    ("Logback", lambda g, a: g == "ch.qos.logback"),
    ("JUnit 5", lambda g, a: g in ("org.junit.jupiter", "org.junit.platform", "org.junit.vintage")),
    ("JUnit 4 (pulled by JUnit 5 vintage engine)", lambda g, a: g == "junit"),
    ("javax.* / Jakarta EE 8 APIs", lambda g, a: g.startswith("javax.") or g.startswith("jakarta.")
        or g.startswith("org.jboss.spec.javax") or a.startswith("javax.") or a.startswith("jakarta.")),
    ("Logging implementations and bridges", lambda g, a: g in ("ch.qos.logback", "org.apache.logging.log4j", "log4j",
        "commons-logging", "org.jboss.logging") or (g == "org.slf4j" and a != "slf4j-api")
        or (g == "org.springframework" and a == "spring-jcl")),
]

COORD = re.compile(r"^\(?([^:\s()]+):([^:\s()]+):([^:\s()]+)(?::([^:\s()]+))?:([^:\s()]+):([a-z]+)(.*)$")


def parse(path):
    """Yield (depth, groupId, artifactId, version, scope, note, chain)."""
    stack = []
    for raw in path.read_text().splitlines():
        if not raw.strip():
            continue
        body = raw.lstrip("|+-\\ ")
        depth = (len(raw) - len(body)) // 3
        if depth == 0:
            stack = [body]
            continue
        m = COORD.match(body)
        if not m:
            continue
        g, a, _type, classifier, v, scope, rest = m.groups()
        if classifier and not scope:
            continue
        coord = f"{g}:{a}:{v}"
        stack = stack[:depth] + [coord]
        note = rest.strip()
        yield depth, g, a, v, scope, note, list(stack)


def main(report_dir):
    report_dir = Path(report_dir)
    out = []
    w = out.append
    w("# S1 dependency conflict report (generated)")
    w("")
    w("Story: b2ec327d-0260-5051-b2b9-e8e046c072a4 | FR-S1-005..FR-S1-010 | S1-AC3, S1-AC4, S1-AC5")
    w("")
    w("Generated by `scripts/s1/dependency-audit.sh` from `dependency-tree-<module>.txt` (resolved graph) and")
    w("`dependency-tree-verbose-<module>.txt` (maven-dependency-plugin 3.6.1 `-Dverbose`). Do not edit by hand.")
    w("")
    w("`Relation` is `direct` when the artifact is declared by the module (depth 1) and `transitive` otherwise.")
    w("")

    resolved = {}
    unique = set()
    for mod in MODULES:
        f = report_dir / f"dependency-tree-{mod}.txt"
        rows = list(parse(f))
        resolved[mod] = rows
        unique.update(f"{r[1]}:{r[2]}:{r[3]}" for r in rows)

    w("## Totals")
    w("")
    w("| Module | Resolved dependency nodes (direct + transitive) | Direct |")
    w("|---|---|---|")
    for mod in MODULES:
        rows = resolved[mod]
        w(f"| {mod} | {len(rows)} | {sum(1 for r in rows if r[0] == 1)} |")
    w(f"| **all modules (unique groupId:artifactId:version)** | {len(unique)} | |")
    w("")

    for title, pred in FOCUS_GROUPS:
        w(f"## {title}")
        w("")
        w("| Module | Artifact | Version | Scope | Relation | Path (nearest parent first) |")
        w("|---|---|---|---|---|---|")
        n = 0
        for mod in MODULES:
            for depth, g, a, v, scope, _note, chain in resolved[mod]:
                if pred(g, a):
                    n += 1
                    rel = "direct" if depth == 1 else "transitive"
                    path = " <- ".join(reversed(chain[1:-1])) or "(declared)"
                    w(f"| {mod} | {g}:{a} | {v} | {scope} | {rel} | {path} |")
        if n == 0:
            w("| _none_ | | | | | |")
        w("")

    w("## Version conflicts in the resolved graph (verbose tree, `omitted for conflict`)")
    w("")
    w("| Module | Artifact | Requested | Resolved | Relation | Requested via (nearest parent first) |")
    w("|---|---|---|---|---|---|")
    seen = set()
    for mod in MODULES:
        f = report_dir / f"dependency-tree-verbose-{mod}.txt"
        for depth, g, a, v, _scope, note, chain in parse(f):
            m = re.search(r"omitted for conflict with ([^;)\s]+)", note)
            if not m:
                continue
            key = (mod, g, a, v, m.group(1), tuple(chain))
            if key in seen:
                continue
            seen.add(key)
            rel = "direct" if depth == 1 else "transitive"
            path = " <- ".join(reversed(chain[1:-1])) or "(declared)"
            w(f"| {mod} | {g}:{a} | {v} | {m.group(1)} | {rel} | {path} |")
    w("")

    w("## Versions overridden by dependency management (verbose tree, `version managed from`)")
    w("")
    w("Only overrides that cross a major version are listed (candidates for Spring Boot 3.x breakage).")
    w("")
    w("| Module | Artifact | Requested | Managed to | Requested via (nearest parent first) |")
    w("|---|---|---|---|---|")
    seen = set()
    for mod in MODULES:
        f = report_dir / f"dependency-tree-verbose-{mod}.txt"
        for _depth, g, a, v, _scope, note, chain in parse(f):
            m = re.search(r"version managed from ([^;]+?)(?:;|\)$|$)", note)
            if not m or m.group(1).split(".")[0] == v.split(".")[0]:
                continue
            key = (mod, g, a, m.group(1), v)
            if key in seen:
                continue
            seen.add(key)
            path = " <- ".join(reversed(chain[1:-1])) or "(declared)"
            w(f"| {mod} | {g}:{a} | {m.group(1)} | {v} | {path} |")
    w("")
    (report_dir / "dependency-summary.md").write_text("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
